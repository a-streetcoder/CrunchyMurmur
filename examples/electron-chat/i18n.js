const browserLocale = typeof navigator === 'undefined' ? 'en' : navigator.language || 'en';
const locale = browserLocale.toLowerCase().split('-')[0];
const catalog = CATALOGS[locale] || CATALOGS.en;

const demoI18n = {
  t(key) {
    return catalog[key] || CATALOGS.en[key] || key;
  },
  apply() {
    document.documentElement.lang = locale;
    for (const element of document.querySelectorAll('[data-i18n]')) {
      element.textContent = this.t(element.dataset.i18n);
    }
    for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
      element.placeholder = this.t(element.dataset.i18nPlaceholder);
    }
  },
};

if (typeof window !== 'undefined') window.demoI18n = demoI18n;
if (typeof module !== 'undefined') module.exports = { CATALOGS, demoI18n };
